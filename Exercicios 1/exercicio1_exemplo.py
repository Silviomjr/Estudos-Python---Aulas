# Script para verificar tipos de variáveis

# Criando variáveis de diferentes tipos
nome = "João"
idade = 25
altura = 1.75

# Verificando o tipo de cada variável e imprimindo o resultado correspondente
if type(nome) == str:
    print("string")

if type(idade) == int:
    print("int")

if type(altura) == float:
    print("float")